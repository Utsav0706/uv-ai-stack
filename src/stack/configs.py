"""Generated configs for the combined system, written to runs/ (never into a project).

Each project reads its config file from CONFIG_PATH, so the stack can change how a
project is wired without touching its repository:

- Gearbox routes through Pitwall (router v4-finetuned = Pitwall's production model,
  10% canary to v4-candidate);
- Scout (only with --scout-via-gearbox) sends its model calls to Gearbox, which
  picks the tier by Scout's task tags. This becomes the default only once the full
  golden-set check through Dyno (integration step I5) has passed.

Relative paths inside each config stay relative to that project's folder, where the
project runs.
"""

from __future__ import annotations

import copy
from pathlib import Path
from typing import Any

import yaml

HEADER = (
    "# Generated by uv-ai-stack ({what}) from {source}. Don't edit; regenerated by `stack up`.\n"
)


def gearbox_via_pitwall(base: dict[str, Any], pitwall_url: str, canary_percent: float) -> dict:
    config = copy.deepcopy(base)
    routing = config.setdefault("routing", {})
    routing["router"] = "v4-finetuned"
    routing["canary"] = {"router": "v4-candidate", "percent": canary_percent}
    routing["pitwall"] = {"url": pitwall_url, "timeout_s": 5}
    return config


def scout_via_gearbox(base: dict[str, Any], gearbox_url: str) -> dict:
    config = copy.deepcopy(base)
    config.setdefault("llm", {})["base_url"] = gearbox_url
    return config


def write(source: Path, out: Path, transform: Any, what: str, *args: Any) -> Path:
    base = yaml.safe_load(source.read_text(encoding="utf-8")) or {}
    config = transform(base, *args)
    out.parent.mkdir(parents=True, exist_ok=True)
    header = HEADER.format(what=what, source=source.as_posix())
    out.write_text(header + yaml.safe_dump(config, sort_keys=False), encoding="utf-8", newline="\n")
    return out
