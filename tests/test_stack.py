from __future__ import annotations

from pathlib import Path

import pytest
import yaml

from stack import configs, runner
from stack import services as svc

ROOT = Path(__file__).resolve().parents[1]


# --- services and order ---------------------------------------------------------------------


def test_default_services_skip_the_uis_and_start_in_dependency_order() -> None:
    chosen = svc.selected(svc.services(ROOT), ui=False)
    names = [s.name for s in svc.start_order(chosen)]
    assert "scout-ui" not in names and "dyno-dashboard" not in names
    assert names.index("mlflow") < names.index("pitwall") < names.index("gearbox")
    assert names.index("prometheus") < names.index("grafana")


def test_scout_waits_for_gearbox_only_when_routed_through_it() -> None:
    direct = {s.name: s for s in svc.services(ROOT)}
    via = {s.name: s for s in svc.services(ROOT, scout_via_gearbox=True)}
    assert direct["scout"].depends_on == () and "CONFIG_PATH" not in direct["scout"].env
    assert via["scout"].depends_on == ("gearbox",)
    assert via["scout"].env["CONFIG_PATH"].endswith("scout-via-gearbox.yaml")
    assert direct["gearbox"].env["CONFIG_PATH"].endswith("gearbox-stack.yaml")


def test_order_refuses_missing_dependencies_and_cycles() -> None:
    a = svc.Service("a", "p", [], 1, "h", depends_on=("b",))
    with pytest.raises(ValueError, match="needs b"):
        svc.start_order([a])
    b = svc.Service("b", "p", [], 2, "h", depends_on=("a",))
    with pytest.raises(ValueError, match="cycle"):
        svc.start_order([a, b])


def test_commands_use_each_projects_own_venv() -> None:
    from stack.pins import load

    projects = {p.name: p for p in load(ROOT / "stack.toml")}
    by_name = {s.name: s for s in svc.services(ROOT, scout_via_gearbox=False)}
    cmd, cwd = svc.command(by_name["gearbox"], projects, ROOT)
    assert cwd.name == "gearbox" and ".venv" in cmd[0] and cmd[1] == "scripts/dev_api.py"
    cmd, cwd = svc.command(by_name["dyno-dashboard"], projects, ROOT)
    assert Path(cmd[0]).stem == "dyno" and cmd[1:] == ["dashboard", "--port", "8503"]


# --- generated configs -----------------------------------------------------------------------


def test_gearbox_config_routes_through_pitwall_and_keeps_the_rest(tmp_path: Path) -> None:
    base = tmp_path / "config.yaml"
    base.write_text(
        yaml.safe_dump(
            {"routing": {"router": "v3-embed", "canary": None}, "cache": {"enabled": True}}
        )
    )
    out = configs.write(
        base, tmp_path / "g.yaml", configs.gearbox_via_pitwall, "x", "http://p:8003", 10
    )
    c = yaml.safe_load(out.read_text(encoding="utf-8"))
    assert c["routing"]["router"] == "v4-finetuned"
    assert c["routing"]["canary"] == {"router": "v4-candidate", "percent": 10}
    assert c["routing"]["pitwall"]["url"] == "http://p:8003" and c["cache"] == {"enabled": True}
    assert out.read_text(encoding="utf-8").startswith("# Generated by uv-ai-stack")


def test_scout_config_points_its_llm_at_gearbox(tmp_path: Path) -> None:
    base = tmp_path / "config.yaml"
    base.write_text(yaml.safe_dump({"llm": {"base_url": None, "models": {"a": 1}}}))
    out = configs.write(base, tmp_path / "s.yaml", configs.scout_via_gearbox, "x", "http://g:8002")
    llm = yaml.safe_load(out.read_text(encoding="utf-8"))["llm"]
    assert llm == {"base_url": "http://g:8002", "models": {"a": 1}}


# --- up / down -------------------------------------------------------------------------------


class World:
    """Fake processes and health checks: a service is healthy once 'started' (or before)."""

    def __init__(
        self,
        healthy_before: set[str] = frozenset(),
        never_healthy: set[str] = frozenset(),
        port_taken: set[int] = frozenset(),
    ) -> None:
        self.up = set(healthy_before)
        self.never = set(never_healthy)
        self.taken = set(port_taken)
        self.started: list[str] = []
        self.t = 0.0

    def start(self, cmd, cwd, env, log) -> int:
        name = Path(log).stem
        self.started.append(name)
        if name not in self.never:
            self.up.add(name)
        return 1000 + len(self.started)

    def healthy(self, url: str) -> bool:
        return url in self.up

    def clock(self) -> float:
        self.t += 10
        return self.t


def services_for(
    names: list[str], deps: dict[str, tuple[str, ...]] | None = None
) -> list[svc.Service]:
    deps = deps or {}
    return [
        svc.Service(n, "p", [], 9000 + i, n, depends_on=deps.get(n, ()), timeout_s=30)
        for i, n in enumerate(names)
    ]


def run_up(tmp_path: Path, world: World, chosen: list[svc.Service]):
    tmp_path.mkdir(parents=True, exist_ok=True)
    exe = tmp_path / "python.exe"
    exe.write_text("")
    commands = {s.name: ([str(exe)], tmp_path) for s in chosen}
    return runner.up(
        tmp_path,
        chosen,
        commands,
        lambda s: None,
        start=world.start,
        is_healthy=world.healthy,
        is_open=lambda p: p in world.taken,
        sleep=lambda s: None,
        clock=world.clock,
    )


def test_up_starts_in_order_and_records_pids(tmp_path: Path) -> None:
    world = World()
    out = run_up(tmp_path, world, services_for(["a", "b"]))
    assert [o.action for o in out] == ["started", "started"] and world.started == ["a", "b"]
    assert runner.read_pids(tmp_path) == {"a": 1001, "b": 1002}


def test_up_reuses_a_healthy_service(tmp_path: Path) -> None:
    world = World(healthy_before={"a"})
    out = run_up(tmp_path, world, services_for(["a", "b"]))
    assert [o.action for o in out] == ["reused", "started"] and world.started == ["b"]
    assert "a" not in runner.read_pids(tmp_path)  # not ours, so `down` won't touch it


def test_up_stops_at_an_unhealthy_service_or_a_taken_port(tmp_path: Path) -> None:
    out = run_up(tmp_path, World(never_healthy={"a"}), services_for(["a", "b"]))
    assert [o.action for o in out] == ["failed"]  # b never started
    out = run_up(tmp_path / "x", World(port_taken={9000}), services_for(["a", "b"]))
    assert out[0].action == "failed" and "in use" in out[0].detail


def test_down_stops_only_what_up_started(tmp_path: Path) -> None:
    runner.write_pids(tmp_path, {"a": 11, "b": 12})
    stopped: list[int] = []
    n = runner.down(tmp_path, lambda s: None, stop=lambda pid: stopped.append(pid) or True)
    assert n == 2 and stopped == [12, 11]  # reverse order: dependents first
    assert runner.read_pids(tmp_path) == {}


def test_missing_venv_is_a_clear_failure(tmp_path: Path) -> None:
    chosen = services_for(["a"])
    commands = {"a": ([str(tmp_path / "nope" / "python.exe")], tmp_path)}
    out = runner.up(
        tmp_path,
        chosen,
        commands,
        lambda s: None,
        start=World().start,
        is_healthy=lambda u: False,
        is_open=lambda p: False,
    )
    assert out[0].action == "failed" and "not found" in out[0].detail
